def build_and_save():
    canonical_skills = set(CANONICAL_SKILL_PATTERNS.keys())
    covered_skills = set()

    for item in RESOURCES_DATA:
        s_name = item["skill_name"]
        if s_name not in canonical_skills:
            raise ValueError(f"Skill '{s_name}' is not in canonical taxonomy!")
        covered_skills.add(s_name)
        item["source"] = "curated_seed"

    payload = {
        "metadata": {
            "source": "curated_seed",
            "version": "1.0",
            "total_resources": len(RESOURCES_DATA),
            "total_skills_covered": len(covered_skills),
            "note": "Curated educational resources for canonical skills. URLs are official documentation or project homepages only.",
        },
        "resources": RESOURCES_DATA,
    }

    out_path = os.path.join("data", "learning", "learning_resources_seed.json")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)

    print(f"Generated {len(RESOURCES_DATA)} resources across {len(covered_skills)} canonical skills into {out_path}")


if __name__ == "__main__":
    build_and_save()
